def draw_truths(field_case, n, seed, field_bbox, anchor):
    rng = np.random.default_rng(seed)
    out = []
    for i in range(n):
        kind = "track" if rng.random() < TRACK_FRACTION else "patch"
        gen = "ours" if i % 2 == 0 else "openoil"
        # release within 12 km of the real slick, kept 60 km inside the field box
        for _ in range(100):
            r = 12.0 * math.sqrt(rng.random())
            th = rng.uniform(0, 2 * math.pi)
            lon = anchor[0] + r * math.cos(th) / (age.KM_PER_DEG_LAT * math.cos(math.radians(anchor[1])))
            lat = anchor[1] + r * math.sin(th) / age.KM_PER_DEG_LAT
            if field_bbox is None:
                break
            w, s, e, nth = field_bbox
            pad = 60.0 / age.KM_PER_DEG_LAT
            if w + pad < lon < e - pad and s + pad < lat < nth - pad:
                break
        t = {"id": f"{field_case}-t{i:03d}", "field": field_case, "generator": gen,
             "kind": kind, "age_h": round(loguniform(rng, *TRUTH_AGE_H), 3),
             "release": [round(lon, 5), round(lat, 5)],
             "wind_coeff": round(float(rng.uniform(0.025, 0.035)), 4),
             "current_scale": round(float(np.clip(rng.normal(1.0, 0.15), 0.5, 1.5)), 3),
             "sigma0_m": round(float(rng.uniform(50.0, 400.0)), 1),
             "oil_type": ["GENERIC MEDIUM CRUDE", "GENERIC INTERMEDIATE FUEL OIL 180",
                          "GENERIC DIESEL"][int(rng.integers(3))],
             "seed": int(rng.integers(1 << 30))}
        if kind == "track":
            t["ship_speed_ms"] = round(float(rng.uniform(3.0, 7.0)), 2)
            t["heading_deg"] = round(float(rng.uniform(0.0, 360.0)), 1)
            t["discharge_h"] = round(float(min(rng.uniform(0.5, 3.0), 0.8 * t["age_h"])), 3)
            t["sigma0_m"] = round(float(rng.uniform(10.0, 30.0)), 1)
        # Truth K: Okubo at the scale this twin will actually reach, times a lognormal factor
        # WIDER than the engine assumes (x/ TRUTH_K_SPREAD vs age.TRACK_OKUBO_SPREAD), so the
        # engine's prior is deliberately a little wrong -- as it will be on a real slick.
        f = math.exp(math.log(TRUTH_K_SPREAD) * rng.normal())
        t["K_m2s"] = round(truth_diffusivity(t["age_h"], t["sigma0_m"], f), 4)
        t["K_factor"] = round(f, 3)
        out.append(t)
    return out


TRUTH_K_SPREAD = 4.0


def truth_diffusivity(age_h, sigma0_m, factor):
    """K = factor x Okubo(l), where l = 4 sqrt(sigma0^2 + 2 K age) is the scale the cloud reaches.
    A fixed point, iterated; converges in a few steps because l^1.15 grows slower than l^2."""
    K = 1.0
    for _ in range(60):
        l = 4.0 * math.sqrt(sigma0_m ** 2 + 2.0 * K * age_h * 3600.0)
        K = float(np.clip(factor * age.okubo_diffusivity_m2s(l), *age.OKUBO_K_BOUNDS_M2S))
    return K


def track_seed(t, n, rng, t0):
    """Positions and seed times of a moving discharge: (lon, lat, hours_before_t0) per particle."""
    tau = rng.uniform(0.0, t["discharge_h"], n)                 # hours after discharge start
    d_m = tau * 3600.0 * t["ship_speed_ms"]
    hd = math.radians(t["heading_deg"])
    coslat = math.cos(math.radians(t["release"][1]))
    lon = t["release"][0] + (d_m * math.sin(hd) + rng.normal(0, t["sigma0_m"], n)) / (
        age.KM_PER_DEG_LAT * 1e3 * coslat)
    lat = t["release"][1] + (d_m * math.cos(hd) + rng.normal(0, t["sigma0_m"], n)) / (
        age.KM_PER_DEG_LAT * 1e3)
    return lon, lat, t["age_h"] - tau


def simulate_ours(t, field, t0, n=2000, timestep_minutes=15):
    import ensemble as ens
    from step import integrate
    rng = np.random.default_rng(t["seed"])
    f = ens.PerturbedField(field, t["current_scale"])
    if t["kind"] == "patch":
        start = age.seed_cloud(t["release"][0], t["release"][1], n, sigma_m=t["sigma0_m"],
                               rng=rng)
        steps = int(round(t["age_h"] * 60 / timestep_minutes)) + 1
        hist, _ = integrate(start, t0 - timedelta(hours=t["age_h"]), f, steps,
                            timestep_minutes, direction="forward", wind_coeff=t["wind_coeff"],
                            diffusivity=t["K_m2s"], rng=rng)
        return hist[-1]
    lon, lat, hb = track_seed(t, n, rng, t0)
    # integrate in groups by seed time: 12 slices of the discharge
    out = []
    edges = np.linspace(hb.min(), hb.max() + 1e-9, 13)
    for a, b in zip(edges[:-1], edges[1:]):
        sel = (hb >= a) & (hb < b)
        if not sel.any():
            continue
        hstart = float((a + b) / 2)
        steps = max(int(round(hstart * 60 / timestep_minutes)), 0) + 1
        hist, _ = integrate(np.column_stack([lon[sel], lat[sel]]),
                            t0 - timedelta(hours=hstart), f, steps, timestep_minutes,
                            direction="forward", wind_coeff=t["wind_coeff"],
                            diffusivity=t["K_m2s"], rng=rng)
        out.append(hist[-1])
    return np.vstack(out)


def cmd_make(a):
    from fields import load_case_field
    d = TWINS / a.field
    d.mkdir(parents=True, exist_ok=True)
    field = load_case_field(a.field, repo_root=REPO)
    t0, anchor = case_anchor(a.field)
    truths = draw_truths(a.field, a.n, a.seed + FIELDS.index(a.field), getattr(field, "bbox", None),
                         anchor)
    features = {}
    tic = time.time()
    for t in truths:
        if t["generator"] != "ours":
            continue
        pos = simulate_ours(t, field, t0)
        feat = particles_to_feature(pos, t["id"])
        features[t["id"]] = feat
        print(f"  {t['id']}  {t['kind']:<5} age {t['age_h']:5.1f} h  K {t['K_m2s']:7.2f}  -> "
              + ("NOT VISIBLE" if feat is None else
                 f"{feat['properties']['area_km2']:.2f} km2 elong "
                 f"{feat['properties']['elongation']} {feat['properties']['discharge_class']}")
              + f"   [{time.time() - tic:.0f} s]", flush=True)
    (d / "truths.json").write_text(json.dumps({"field": a.field, "t0": t0.isoformat(),
                                               "truths": truths}, indent=1))
    (d / "features_ours.json").write_text(json.dumps(features))
    (d / "openoil_truth_request.json").write_text(json.dumps({
        "field": a.field, "t0": t0.isoformat().replace("+00:00", "Z"),
        "truths": [t for t in truths if t["generator"] == "openoil"]}, indent=1))
    print(f"wrote {d}  ({sum(1 for t in truths if t['generator'] == 'ours')} ours, "
          f"{sum(1 for t in truths if t['generator'] == 'openoil')} for OpenOil)")


