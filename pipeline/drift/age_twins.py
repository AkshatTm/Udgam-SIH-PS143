#!/usr/bin/env python3
"""Stage 2 age engine v2 -- synthetic twins: the only way to MEASURE an age engine's accuracy.

There is one real slick in the library with a documented release time (Huntington, 2.8 h).
One is not a validation set. So the accuracy claim is made on twins: slicks simulated with a
KNOWN age through the REAL current and wind fields of the six cases, turned into SAR-like
polygons, and handed to the real engine as if Stage 1 had detected them.

    python pipeline/drift/age_twins.py make      --field case-jacksonville-2024 --n 24
    odenv\\Scripts\\python pipeline/drift/opendrift_twins.py --field case-jacksonville-2024
    python pipeline/drift/age_twins.py prepare   --field case-jacksonville-2024
    odenv\\Scripts\\python pipeline/drift/opendrift_age.py --case case-jacksonville-2024 --batch
    python pipeline/drift/age_twins.py score     --field case-jacksonville-2024 --jobs 7
    python pipeline/drift/age_twins.py calibrate                # all fields -> age_calibration.json
    python pipeline/drift/age_twins.py report                   # -> docs/evaluation/stage2-age-engine.md

THE INVERSE CRIME, AND HOW THIS AVOIDS IT
    Scoring a model on data it generated itself measures nothing but its own noise. Half the
    twins are generated by OUR model and half by OpenDrift OpenOil, and three scores are kept:

      cross_ours     OpenOil truths, scored with our model only (E1 + E4)
      cross_openoil  our truths, scored with OpenOil only (E2 + E4)
      mixture        every twin, scored the way production scores (E1 (+) E2, E3, E4)

    The observation-error sigmas are fitted on the two CROSS settings only. The mixture number
    is reported beside them and is expected to be the most flattering of the three.

TRUTH PARAMETERS ARE DRAWN WIDER THAN THE ENGINE ASSUMES
    Truth diffusivity is Okubo's K at the scale the twin actually reaches, times a lognormal
    factor of x/ 4 -- wider than the x/ 3 the engine assumes -- so the engine's K prior is
    deliberately a little wrong, as it will be on a real slick. (A first draft drew K
    log-uniformly over [0.05, 100]; that made age and K fully degenerate and is physically
    unrealistic for km-scale patches. See age.okubo_member_ks.) Truth age is log-uniform on
    [1.5, 66] h, matching the engine's log-uniform prior, so coverage is measured under the
    distribution the posterior claims to describe.

Everything expensive is stored (candidate shape curves per twin), so `calibrate` refits sigmas
and weights in seconds without rerunning a single particle.
"""
