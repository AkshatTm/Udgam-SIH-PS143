def loguniform(rng, lo, hi):
    return float(math.exp(rng.uniform(math.log(lo), math.log(hi))))


def parse_ts(s):
    from datetime import datetime
    return datetime.fromisoformat(str(s).replace("Z", "+00:00"))


def case_anchor(field_case):
    """t0 and the case's own slick centroid -- twins are released around where real oil was."""
    from slick import merge_oil_features
    cdir = REPO / "cases" / field_case
    meta = json.loads((cdir / "meta.json").read_text())
    feat, _ = merge_oil_features(json.loads((cdir / "detections.geojson").read_text()))
    return parse_ts(meta["detection_time"]), tuple(feat["properties"]["centroid"])


# ---------------------------------------------------------------------------------------
# particles -> a SAR-like polygon
# ---------------------------------------------------------------------------------------

def particles_to_feature(pos, feature_id, thresh_frac=0.2, smooth_px=1.5, min_px_m=20.0):
    """The polygon Stage 1 would have drawn around this cloud, or None if nothing is visible.

    Density on a local metric grid, gaussian-smoothed, thresholded at `thresh_frac` of its peak
    (SAR sees where oil is thick enough to damp waves, not where the last particle went),
    largest connected component, vectorised. Pixel size adapts to the cloud so a 2000-particle
    cloud is neither a speckle field nor one blocky pixel.
    """
    from scipy.ndimage import gaussian_filter, label
    from rasterio.features import shapes
    from rasterio.transform import Affine

    p = np.asarray(pos, dtype=np.float64)
    p = p[np.all(np.isfinite(p), axis=1)]
    if p.shape[0] < 30:
        return None
    lon0, lat0 = float(np.median(p[:, 0])), float(np.median(p[:, 1]))
    xy = age._local_metres(p, lon0, lat0)
    # Pixel size from LOCAL particle spacing (median distance to the 8th neighbour), not from
    # the whole cloud's spread: a 50 km curving ship track has a km-scale PCA minor axis, and
    # pixels sized from that are wider than the track itself -- which inflated a 0.7 km-wide
    # twin into a 75 km2 blob and would have fed the width estimator a width set by the grid.
    from scipy.spatial import cKDTree
    d8 = float(np.median(cKDTree(xy).query(xy, k=9)[0][:, -1]))
    px = float(np.clip(0.6 * d8, min_px_m, 400.0))
    lo_xy = xy.min(axis=0) - 6 * px
    hi_xy = xy.max(axis=0) + 6 * px
    nx = int(math.ceil((hi_xy[0] - lo_xy[0]) / px))
    ny = int(math.ceil((hi_xy[1] - lo_xy[1]) / px))
    if nx * ny > 16_000_000:
        return None
    H, _, _ = np.histogram2d(xy[:, 1], xy[:, 0], bins=[ny, nx],
                             range=[[lo_xy[1], lo_xy[1] + ny * px], [lo_xy[0], lo_xy[0] + nx * px]])
    H = gaussian_filter(H[::-1, :], smooth_px)          # row 0 = north
    mask = H >= thresh_frac * H.max()
    lab, n = label(mask)
    if n == 0:
        return None
    big = lab == (1 + int(np.argmax(np.bincount(lab.ravel())[1:])))
    tr = Affine(px, 0.0, lo_xy[0], 0.0, -px, lo_xy[1] + ny * px)
    ring = None
    for geom, val in shapes(big.astype("uint8"), mask=big, transform=tr):
        if val == 1:
            ring = np.asarray(geom["coordinates"][0], dtype=np.float64)
            break
    if ring is None or ring.shape[0] < 4:
        return None
    coslat = math.cos(math.radians(lat0))
    lonlat = np.column_stack([lon0 + ring[:, 0] / (coslat * age.KM_PER_DEG_LAT * 1e3),
                              lat0 + ring[:, 1] / (age.KM_PER_DEG_LAT * 1e3)])
    area_km2 = float(big.sum()) * px * px / 1e6
    L, d = age.polygon_major_axis_km(lonlat)
    elong = max(1.0, (d.get("bbox_aspect") or 1.0))
    axis = L if L else 0.0
    perim = float(np.sum(np.hypot(np.diff(ring[:, 0]), np.diff(ring[:, 1])))) / 1000.0
    straight = float(np.clip(2.0 * axis / perim, 0.0, 1.0)) if perim > 0 else 1.0
    if elong >= CHRONIC_ELONGATION:
        dc = "chronic" if straight >= STRAIGHTNESS_MIN else "unknown"
    elif elong < ACUTE_ELONGATION:
        dc = "acute"
    else:
        dc = "unknown"
    rr, cc = np.nonzero(big)
    cx = lo_xy[0] + (cc.mean() + 0.5) * px
    cy = lo_xy[1] + ny * px - (rr.mean() + 0.5) * px
    centroid = [round(lon0 + cx / (coslat * age.KM_PER_DEG_LAT * 1e3), 5),
                round(lat0 + cy / (age.KM_PER_DEG_LAT * 1e3), 5)]
    return {"type": "Feature",
            "geometry": {"type": "Polygon",
                         "coordinates": [np.round(lonlat, 6).tolist()]},
            "properties": {"id": feature_id, "classification": "oil", "confidence": 1.0,
                           "area_km2": round(area_km2, 4), "elongation": round(elong, 2),
                           "shape_class": "linear" if elong > 3 else "blob",
                           "discharge_class": dc, "centroid": centroid,
                           "twin_px_m": round(px, 1)}}


