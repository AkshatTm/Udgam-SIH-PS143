def load_all():
    rows = []
    for f in FIELDS:
        d = TWINS / f
        if not (d / "scored.json").exists():
            continue
        truths = {t["id"]: t for t in json.loads((d / "truths.json").read_text())["truths"]}
        req = json.loads((d / "age_batch_request.json").read_text())
        scored = json.loads((d / "scored.json").read_text())
        od = None
        odp = d / "opendrift_age_batch.npz"
        if odp.exists():
            z = np.load(odp, allow_pickle=False)
            od = {"ids": [str(x) for x in z["ids"]], "L": z["L_km"], "W": z["W_km"],
                  "B": z["bearing_deg"], "SF": z["surface_fraction"],
                  "ch": z["candidate_hours"]}
        for tid, s in scored.items():
            r = dict(s)
            r["truth"] = truths[tid]
            r["field"] = f
            r["ch"] = req["candidate_hours"]
            if od is not None and tid in od["ids"]:
                k = od["ids"].index(tid)
                r["curves_od"] = {"L": od["L"][k], "W": od["W"][k], "B": od["B"][k],
                                  "SF": od["SF"][k], "ch": od["ch"]}
            rows.append(r)
    return rows


def posterior_for(r, setting, p):
    """Rebuild one twin's posterior from stored curves under parameters `p` and a setting."""
    ll1 = ll2 = ll3 = None
    o = r["obs"]
    c = r.get("curves_ours")
    if setting in ("mixture", "cross_ours") and c and o["L"]:
        ll1 = age.shape_loglik(r["ch"], c["L_km"], c["W_km"], c["bearing_deg"], o["L"], o["W"],
                               o["B"], p["sigma_L"], p["sigma_W"], p["kappa"])
    od = r.get("curves_od")
    if setting in ("mixture", "cross_openoil") and od is not None and o["L"]:
        ll2 = age.shape_loglik(od["ch"], od["L"], od["W"], od["B"], o["L"], o["W"], o["B"],
                               p["sigma_L"], p["sigma_W"], p["kappa"])
        if setting == "mixture":
            ll3 = age.detectability_loglik(od["ch"], od["SF"])
    w = p["weights"]
    llt = None if r.get("track_loglik") is None else np.asarray(r["track_loglik"])
    patch, pu = AP.fuse([("shape", AP.mix_logliks([ll1, ll2]), w["shape"]),
                         ("detect", ll3, w["detect"])])
    track, tu = AP.fuse([("track", llt, w["track"]), ("detect", ll3, w["detect"])])
    patch = None if pu == ["detect"] else patch
    track = None if tu == ["detect"] else track
    dc = r.get("discharge_class")
    if dc == "acute":
        post = patch
    elif dc == "chronic":
        post = track
    else:
        post = AP.average_posteriors([patch, track])
    return AP.summarise(post, []), post


def settings_for(r):
    s = ["mixture"]
    if r["truth"]["generator"] == "openoil":
        s.append("cross_ours")
    if r["truth"]["generator"] == "ours" and r.get("curves_od") is not None:
        s.append("cross_openoil")
    return s


def evaluate(rows, p, setting):
    """Coverage, width, log score and refusal rate over `rows` under one setting."""
    cov, width, logs, pits, n_ref, n = [], [], [], [], 0, 0
    for r in rows:
        if setting not in settings_for(r):
            continue
        n += 1
        summ, post = posterior_for(r, setting, p)
        if post is None or summ["status"] != "ok":
            n_ref += 1
            continue
        t = r["truth"]["age_h"]
        lo, hi = summ["hpd80"]
        cov.append(lo <= t <= hi)
        width.append(math.log(hi / max(lo, 0.5)))
        k = int(np.argmin(np.abs(AP.AGE_GRID_H - t)))
        logs.append(math.log(max(post[k], 1e-12)))
        pits.append(AP.pit(post, t))
    return {"n": n, "answered": len(cov), "refused": n_ref,
            "coverage80": None if not cov else round(float(np.mean(cov)), 3),
            "median_log_width": None if not width else round(float(np.median(width)), 3),
            "mean_log_score": None if not logs else round(float(np.mean(logs)), 3),
            "pits": [round(x, 3) for x in pits]}


def fit(rows):
    """Grid search: sigmas on the CROSS settings; weights by coverage-penalised log score."""
    best = None
    for sL in (0.2, 0.3, 0.45, 0.65, 0.9):
        for sW in (0.35, 0.5, 0.75, 1.0):
            for kap in (0.0, 0.5, 1.0):
                for ws in (0.5, 0.75, 1.0):
                    for wt in (0.25, 0.5, 1.0):
                        p = {"sigma_L": sL, "sigma_W": sW, "kappa": kap,
                             "weights": {"shape": ws, "detect": 0.5, "track": wt,
                                         "surrogate": 0.0}}
                        score, ok = 0.0, True
                        for st in ("cross_ours", "cross_openoil"):
                            e = evaluate(rows, p, st)
                            if not e["answered"]:
                                continue
                            score += e["mean_log_score"] - 10.0 * abs(e["coverage80"] - 0.80)
                        if best is None or score > best[0]:
                            best = (score, p)
    return best[1]


def cmd_calibrate(a):
    rows = load_all()
    fields = sorted({r["field"] for r in rows})
    print(f"{len(rows)} scored twins across {len(fields)} fields")
    if len(fields) < 2:
        raise SystemExit("need at least two scored fields for leave-one-field-out")
    held = {st: [] for st in ("mixture", "cross_ours", "cross_openoil")}
    for f in fields:
        p = fit([r for r in rows if r["field"] != f])
        test = [r for r in rows if r["field"] == f]
        for st in held:
            e = evaluate(test, p, st)
            e["field"] = f
            held[st].append(e)
        print(f"  held out {f}: fitted sigma_L {p['sigma_L']} sigma_W {p['sigma_W']} "
              f"kappa {p['kappa']} w {p['weights']}")
    final = fit(rows)
    summary = {}
    for st, es in held.items():
        ans = sum(e["answered"] for e in es)
        cov = sum((e["coverage80"] or 0) * e["answered"] for e in es)
        summary[st] = {"n": sum(e["n"] for e in es), "answered": ans,
                       "refused": sum(e["refused"] for e in es),
                       "coverage80_heldout": None if not ans else round(cov / ans, 3),
                       "per_field": es}
    cal = {"sigma_L": final["sigma_L"], "sigma_W": final["sigma_W"], "kappa": final["kappa"],
           "weights": final["weights"],
           "coverage80": summary["mixture"]["coverage80_heldout"],
           "coverage80_cross": {k: summary[k]["coverage80_heldout"]
                                for k in ("cross_ours", "cross_openoil")},
           "n_twins": len(rows), "fields": fields,
           "method": "leave-one-field-out grid search; sigmas fitted on cross-model twins only",
           "fitted": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    age.CALIBRATION_PATH.write_text(json.dumps(cal, indent=1))
    (TWINS / "calibration_report.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk != "per_field"}
                      for k, v in summary.items()}, indent=1))
    print(f"wrote {age.CALIBRATION_PATH}")


