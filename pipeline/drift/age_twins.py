def candidate_hours():
    lo, hi, st = (float(x) for x in CANDIDATES.split(":"))
    return sorted({1.0, *[round(x, 6) for x in np.arange(lo, hi + 1e-9, st)]})


def load_features(d):
    feats = json.loads((d / "features_ours.json").read_text())
    oo = d / "openoil_truths.npz"
    if oo.exists():
        z = np.load(oo, allow_pickle=False)
        ids = [str(x) for x in z["ids"]]
        for k, tid in enumerate(ids):
            sel = z["owner"] == k
            feats[tid] = particles_to_feature(np.column_stack([z["lon"][sel], z["lat"][sel]]),
                                              tid)
    return feats


def cmd_prepare(a):
    from fields import load_case_field
    import coastline
    d = TWINS / a.field
    truths = json.loads((d / "truths.json").read_text())
    t0 = parse_ts(truths["t0"])
    feats = load_features(d)
    field = load_case_field(a.field, repo_root=REPO)
    land = coastline.is_land if coastline.available() else None
    ch = candidate_hours()
    cov = age.field_time_coverage(a.field, REPO)
    ch, _, _ = age.clip_candidates_to_coverage(ch, t0, cov)
    batch = []
    for t in truths["truths"]:
        f = feats.get(t["id"])
        if f is None:
            continue
        rel = age.control_release_points(field, f, t0, ch, seed=7, is_land=land)
        batch.append({"id": t["id"], "okubo_scale_m": age.slick_scale_m(f),
                      "release_points": [[round(x, 5), round(y, 5)] for x, y in rel]})
    (d / "features_all.json").write_text(json.dumps(feats))
    req = {"case": a.field, "t0": t0.isoformat().replace("+00:00", "Z"),
           "candidate_hours": ch, "batch": batch, "timestep_minutes": 15}
    (d / "age_batch_request.json").write_text(json.dumps(req, indent=1))
    print(f"prepared {len(batch)} visible twins ({len(truths['truths']) - len(batch)} not "
          f"visible) -> {d / 'age_batch_request.json'}")


