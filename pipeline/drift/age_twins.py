def _score_one(args):
    field_case, t0_iso, ch, feat, rel = args
    from fields import load_case_field
    field = load_case_field(field_case, repo_root=REPO)
    t0 = parse_ts(t0_iso)
    L, ad = age.slick_major_axis_km(feat)
    props = feat["properties"]
    band, sd = age.shear_dispersion_age(
        field, props["centroid"][0], props["centroid"][1], t0, L, ch,
        n_particles=SCORE_PARTICLES, n_members=SCORE_MEMBERS, seed=11,
        discharge_class="unknown", release_points=rel,
        observed_width_km=ad.get("bbox_width_km"), observed_bearing_deg=ad.get("orientation_deg"))
    _, td = age.track_age(feat, props.get("discharge_class"))
    return {"id": props["id"], "obs": {"L": L, "W": ad.get("bbox_width_km"),
                                       "B": ad.get("orientation_deg")},
            "discharge_class": props.get("discharge_class"),
            "curves_ours": sd.get("shape_curves"),
            "track_loglik": td.get("loglik"), "track_skipped": td.get("skipped")}


def cmd_score(a):
    from concurrent.futures import ProcessPoolExecutor
    d = TWINS / a.field
    req = json.loads((d / "age_batch_request.json").read_text())
    feats = json.loads((d / "features_all.json").read_text())
    done_path = d / "scored.json"
    done = json.loads(done_path.read_text()) if done_path.exists() else {}
    jobs = [(a.field, req["t0"], req["candidate_hours"], feats[b["id"]], b["release_points"])
            for b in req["batch"] if b["id"] not in done]
    print(f"scoring {len(jobs)} twins on {a.jobs} processes ({len(done)} already done)")
    tic = time.time()
    with ProcessPoolExecutor(max_workers=a.jobs) as ex:
        for r in ex.map(_score_one, jobs):
            done[r["id"]] = r
            done_path.write_text(json.dumps(done))
            print(f"  {r['id']}  [{time.time() - tic:.0f} s]", flush=True)


